"""Generate a same-origin offline app cache after Flutter's web build."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "build" / "web"
assets = sorted(
    path for path in root.rglob("*")
    if path.is_file() and path.name not in {"sw.js", "flutter_service_worker.js"}
    and path.suffix != ".map"
)
if not (root / "main.dart.js").is_file():
    raise SystemExit("Build the Flutter web app before creating the offline cache.")
digest = hashlib.sha256()
for path in assets:
    digest.update(path.relative_to(root).as_posix().encode())
    digest.update(path.read_bytes())
version = digest.hexdigest()[:16]
paths = ["./"] + [path.relative_to(root).as_posix() for path in assets]
worker = """// Generated by tool/offline_cache.py. Do not edit the build output.
const PREFIX = 'tally-' + new URL(self.registration.scope).pathname + '-';
const CACHE = PREFIX + 'VERSION';
const ASSETS = ASSET_LIST;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const saved = await cache.match(event.request);
    if (saved) return saved;
    try { return await fetch(event.request); }
    catch (error) {
      if (event.request.mode === 'navigate') {
        const shell = await cache.match(new URL('index.html', self.registration.scope));
        if (shell) return shell;
      }
      throw error;
    }
  })());
});
""".replace("VERSION", version).replace("ASSET_LIST", json.dumps(paths))
(root / "sw.js").write_text(worker)
print(f"Offline cache generated: {len(paths)} resources, version {version}")
